"""Streaming checksums used before loading or reusing downloaded data."""

from pathlib import Path
import hashlib


def sha256_file(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()
