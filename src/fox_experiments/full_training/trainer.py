"""A small torchrun/DDP trainer with resumable state and paired interventions.

The readable shared FoX model supplies the architecture; only attention execution
uses the authors' Triton implementation. This is not their Lightning trainer.
"""

from __future__ import annotations

from contextlib import nullcontext
from dataclasses import asdict
import hashlib
import json
import math
import os
from pathlib import Path
import random
import time

import numpy as np
import torch
import torch.distributed as dist
from torch import nn
from torch.nn.parallel import DistributedDataParallel

from .config import budget, task_config


class LossModule(nn.Module):
    """Expose chunked LM loss through DDP.forward, retaining DDP gradient hooks."""

    def __init__(self, model, logit_chunk):
        super().__init__()
        self.model, self.logit_chunk = model, logit_chunk

    def forward(self, tokens, targets, weights):
        # Returning a weighted sum lets the trainer normalize over the *whole*
        # global accumulated batch even when answer weights differ across ranks.
        return (
            self.model.loss(
                tokens, targets, loss_mask=weights, logit_chunk=self.logit_chunk
            )
            * weights.sum()
        )


def schedule_values(config, arm, step, total_steps, rate):
    """Schedules use completed optimizer updates, never microbatches or epochs."""
    task = task_config(config)
    if arm == "paper_adamw":
        warmup = min(1.0, (step + 1) / max(1, config.warmup_steps))
        fraction = max(0.0, step - config.warmup_steps) / max(
            1, total_steps - config.warmup_steps
        )
        multiplier = warmup * 0.5 * (1.0 + math.cos(math.pi * min(1.0, fraction)))
    else:
        multiplier = (1 + step / task.lr_offset) ** (-task.lr_power)
    epsilon = task.eps0
    if arm == "adam_annealed":
        epsilon *= math.exp(-task.epsilon_decay * step)
        if epsilon < np.finfo(np.float32).tiny:
            raise FloatingPointError(
                "Scheduled epsilon left normal FP32 range; shorten this run or slow epsilon decay"
            )
    return rate * multiplier, epsilon


def _rng_state(device):
    return {
        "python": random.getstate(),
        "numpy": np.random.get_state(),
        "torch": torch.get_rng_state(),
        "cuda": torch.cuda.get_rng_state(device) if device.type == "cuda" else None,
    }


def _restore_rng(state, device):
    random.setstate(state["python"])
    np.random.set_state(state["numpy"])
    torch.set_rng_state(state["torch"])
    if device.type == "cuda":
        torch.cuda.set_rng_state(state["cuda"], device)


def load_model(checkpoint, device="cpu", backend=None):
    """Read checkpoints generated by this repository; do not load untrusted .pt files."""
    from fox_experiments.models import FoXLM, ModelConfig

    saved = torch.load(checkpoint, map_location="cpu", weights_only=False)
    model_info = dict(saved["model_config"])
    if backend is not None:
        model_info["attention_backend"] = backend
    model = FoXLM(ModelConfig(**model_info))
    model.load_state_dict(saved["model"])
    return model.to(device), saved


def _save_checkpoint(path, payload):
    temporary = path.with_suffix(path.suffix + ".tmp")
    torch.save(payload, temporary)
    os.replace(temporary, path)


def _write_json(path, value):
    path.write_text(json.dumps(value, indent=2, default=str, allow_nan=False))


def _file_digest(path):
    digest = hashlib.sha256()
    with open(path, "rb") as stream:
        for block in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _implementation_digest():
    root = Path(__file__).parents[1]
    digest = hashlib.sha256()
    for path in sorted(root.rglob("*.py")):
        digest.update(str(path.relative_to(root)).encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()


def _data_identity(root):
    paths = ("source.json", "train.zarr/.zarray", "heldout.zarr/.zarray")
    return {
        name: _file_digest(Path(root) / name)
        for name in paths
        if (Path(root) / name).is_file()
    }


def gate_diagnostics(model, optimizer):
    """Cheap gate/moment diagnostics; never concatenate full-model moments."""
    gate = model.blocks[0].attn.gate
    report = {}
    for name, parameter in gate.named_parameters():
        values = parameter.detach().float()
        report[f"first_gate_{name}_mean"] = float(values.mean())
        report[f"first_gate_{name}_min"] = float(values.min())
        report[f"first_gate_{name}_max"] = float(values.max())
        state = optimizer.state.get(parameter, {})
        if "exp_avg_sq" in state:
            group = next(
                g
                for g in optimizer.param_groups
                if any(p is parameter for p in g["params"])
            )
            moment = (
                state["exp_avg_sq"] / (1 - group["betas"][1] ** float(state["step"]))
            ).sqrt()
            epsilon = group["eps"]
            report[f"first_gate_{name}_epsilon_dominated_fraction"] = float(
                (moment <= epsilon).float().mean()
            )
            report[f"first_gate_{name}_zero_second_moment_fraction"] = float(
                (moment == 0).float().mean()
            )
    if gate.mode == "factorized_constant":
        raw = gate.u.detach().float() * gate.v.detach().float()
    elif gate.mode == "direct_constant":
        raw = gate.b.detach().float()
    else:
        raw = None
    if raw is not None:
        report["first_gate_decay_mean"] = float(
            torch.nn.functional.softplus(raw).mean()
        )
        report["first_gate_positive_raw_fraction"] = float((raw > 0).float().mean())
    return report


def train(
    config,
    *,
    stage,
    gate,
    arm="adam_annealed",
    run_dir=None,
    init_from=None,
    lr=None,
    steps=None,
    allow_cpu=False,
    corpus=None,
    stop_after=None,
):
    """Train one source or continuation; rerun the identical command to resume.

    `stop_after` is a controlled interruption hook used in resume tests. It does
    not change the run signature or the scheduler's intended horizon.
    """
    from fox_experiments.models import FoXLM, ModelConfig
    from fox_experiments.data import LatestWriteData
    from fox_experiments.training.optimizers import make_optimizer
    from .data import NativeCorpus
    import tiktoken

    config.validate()
    if stage not in ("source", "continuation"):
        raise ValueError("stage must be source or continuation")
    if stage == "source" and gate not in ("direct_constant", "original_data"):
        raise ValueError("Acquire a direct_constant or original_data source first")
    if stage == "continuation" and not init_from:
        raise ValueError("Continuation requires an explicit shared source checkpoint")
    if stage == "source":
        arm = "paper_adamw"
    world = int(os.environ.get("WORLD_SIZE", 1))
    rank = int(os.environ.get("RANK", 0))
    local_rank = int(os.environ.get("LOCAL_RANK", 0))
    if world != config.expected_world_size:
        raise ValueError(
            f"Config requires {config.expected_world_size} ranks, launcher supplies {world}; changing ranks changes token budgets"
        )
    if torch.cuda.is_available():
        torch.cuda.set_device(local_rank)
        device = torch.device("cuda", local_rank)
        if config.precision == "bf16" and not torch.cuda.is_bf16_supported():
            raise RuntimeError("This full config requires a BF16-capable GPU")
    elif (
        allow_cpu
        and config.precision == "fp32"
        and config.model.get("attention_backend") == "sdpa"
    ):
        device = torch.device("cpu")
        torch.set_num_threads(min(4, os.cpu_count() or 1))
    else:
        raise RuntimeError(
            "Full training requires CUDA; use the downscaled notebook on Colab"
        )
    initialized_here = world > 1 and not dist.is_initialized()
    if initialized_here:
        dist.init_process_group("nccl" if device.type == "cuda" else "gloo")
    try:
        return _train_inner(
            config,
            stage,
            gate,
            arm,
            run_dir,
            init_from,
            lr,
            steps,
            stop_after,
            corpus,
            device,
            world,
            rank,
            FoXLM,
            ModelConfig,
            LatestWriteData,
            make_optimizer,
            NativeCorpus,
            tiktoken,
        )
    except Exception as error:
        if rank == 0:
            directory = Path(
                run_dir
                or Path(config.output_root) / f"seed{config.seed}_{stage}_{gate}_{arm}"
            )
            directory.mkdir(parents=True, exist_ok=True)
            _write_json(
                directory / "failure.json",
                {
                    "type": type(error).__name__,
                    "message": str(error),
                    "recovery": "The last atomic checkpoint is retained; correct the cause before resuming.",
                },
            )
        raise
    finally:
        if initialized_here:
            dist.destroy_process_group()


def _train_inner(
    config,
    stage,
    gate,
    arm,
    run_dir,
    init_from,
    lr,
    steps,
    stop_after,
    corpus,
    device,
    world,
    rank,
    FoXLM,
    ModelConfig,
    LatestWriteData,
    make_optimizer,
    NativeCorpus,
    tiktoken,
):
    arm = "paper_adamw" if stage == "source" else arm
    task = task_config(config)
    rate = (
        lr
        if lr is not None
        else config.learning_rates["source" if stage == "source" else arm]
    )
    total = (
        steps
        if steps is not None
        else (
            config.pretrain_steps + config.acquisition_steps
            if stage == "source"
            else config.continuation_steps
        )
    )
    if total < 1 or rate <= 0:
        raise ValueError("Steps and learning rate must be positive")
    schedule_values(config, arm, total - 1, total, rate)
    directory = Path(
        run_dir or Path(config.output_root) / f"seed{config.seed}_{stage}_{gate}_{arm}"
    )
    directory.mkdir(parents=True, exist_ok=True)
    specification = {
        "config": config.to_dict(),
        "stage": stage,
        "gate": gate,
        "arm": arm,
        "learning_rate": rate,
        "total_steps": total,
        "init_from": str(Path(init_from).resolve()) if init_from else None,
        "world_size": world,
        "implementation_sha256": _implementation_digest(),
        "source_checkpoint_sha256": _file_digest(init_from) if init_from else None,
        "data_metadata_sha256": _data_identity(config.data_root),
    }
    signature = hashlib.sha256(
        json.dumps(specification, sort_keys=True).encode()
    ).hexdigest()
    checkpoint = directory / "last.pt"
    random.seed(config.seed + rank)
    np.random.seed(config.seed + rank)
    torch.manual_seed(config.seed + rank)
    if checkpoint.exists():
        model, saved = load_model(checkpoint, device)
        if saved["signature"] != signature:
            raise ValueError("Resume specification changed; use a new run directory")
    else:
        saved = None
        if (directory / "config.json").exists():
            previous = json.loads((directory / "config.json").read_text())
            if previous != specification:
                raise ValueError(
                    "Run directory already contains a different experiment"
                )
        if init_from:
            model, source = load_model(init_from)
            if source["specification"]["stage"] != "source":
                raise ValueError("init_from must be an acquired source checkpoint")
            if source["step"] != source["specification"]["total_steps"]:
                raise ValueError(
                    "Source is incomplete; finish its scheduled updates before branching"
                )
            expected_model = ModelConfig(
                **config.model,
                seed=config.seed,
                gate_mode=source["model_config"]["gate_mode"],
            )
            if asdict(expected_model) != source["model_config"]:
                raise ValueError(
                    "Source architecture/initialization config differs from requested branch"
                )
            model = model.converted(gate).to(device)
        else:
            model = FoXLM(
                ModelConfig(**config.model, seed=config.seed, gate_mode=gate)
            ).to(device)
    optimizer = make_optimizer(model, task, arm, rate)
    completed, accumulated_lr, history = 0, 0.0, []
    if saved:
        optimizer.load_state_dict(saved["optimizer"])
        completed, accumulated_lr, history = (
            saved["step"],
            saved["scheduler"]["S"],
            saved["history"],
        )
        if len(saved["rng_by_rank"]) != world:
            raise ValueError("Exact resume requires the original world size")
        _restore_rng(saved["rng_by_rank"][rank], device)
    # Prime/download tokenizer only on rank zero before the others open its cache.
    if rank == 0:
        tokenizer = tiktoken.get_encoding("gpt2")
    if world > 1:
        dist.barrier()
    if rank != 0:
        tokenizer = tiktoken.get_encoding("gpt2")
    corpus = (
        corpus
        if corpus is not None
        else NativeCorpus(config.data_root, config.strict_data)
    )
    data = LatestWriteData(corpus, tokenizer)
    wrapped = LossModule(model, config.logit_chunk)
    if world > 1:
        wrapped = DistributedDataParallel(
            wrapped,
            device_ids=[device.index] if device.type == "cuda" else None,
            broadcast_buffers=False,
        )
    if rank == 0:
        _write_json(directory / "config.json", specification)
        _write_json(
            directory / "environment.json",
            {
                "torch": torch.__version__,
                "world_size": world,
                "device": str(device),
                "gpu": (
                    torch.cuda.get_device_name(device)
                    if device.type == "cuda"
                    else None
                ),
                "parameter_count": sum(p.numel() for p in model.parameters()),
                "budget": budget(config, world),
                "attention_pruning": False,
                "precision": config.precision,
            },
        )
    prior_seconds = saved.get("seconds", 0.0) if saved else 0.0
    tic = time.perf_counter()
    for step in range(completed, total):
        model.train()
        optimizer.zero_grad(set_to_none=True)
        current_lr, epsilon = schedule_values(config, arm, step, total, rate)
        for group in optimizer.param_groups:
            group["lr"] = current_lr * group.get("base_multiplier", 1.0)
            if arm.startswith("adam"):
                group["eps"] = epsilon
        probability = (
            0.0
            if stage == "source" and step < config.pretrain_steps
            else task.mixture_probability
        )
        # Common seeds and global microbatch IDs pair training examples across
        # gate/optimizer branches. Rank streams are distinct and reproducible.
        phase_seed = config.seed + (10000 if stage == "source" else 30000)
        batches = [
            data.batch(
                task,
                step,
                rank * task.accumulation + micro,
                phase_seed,
                task_probability=probability,
            )
            for micro in range(task.accumulation)
        ]
        denominator = torch.tensor(
            sum(float(batch[2].sum()) for batch in batches), device=device
        )
        if world > 1:
            dist.all_reduce(denominator)
        numerator_total = torch.zeros((), device=device)
        for micro, batch in enumerate(batches):
            x, y, weights = (entry.to(device, non_blocking=True) for entry in batch)
            sync = (
                wrapped.no_sync()
                if world > 1 and micro < task.accumulation - 1
                else nullcontext()
            )
            amp = (
                torch.autocast("cuda", dtype=torch.bfloat16)
                if config.precision == "bf16"
                else nullcontext()
            )
            with sync:
                with amp:
                    numerator = wrapped(x, y, weights)
                    loss = numerator * world / denominator
                finite = torch.tensor(int(torch.isfinite(loss).item()), device=device)
                if world > 1:
                    dist.all_reduce(finite, op=dist.ReduceOp.MIN)
                if not finite.item():
                    raise FloatingPointError(
                        f"Nonfinite loss at update {step + 1}; last.pt remains the last completed save"
                    )
                loss.backward()
            numerator_total += numerator.detach()
        norm = torch.nn.utils.clip_grad_norm_(
            model.parameters(), 1.0 if arm == "paper_adamw" else float("inf")
        )
        finite = torch.tensor(int(torch.isfinite(norm).item()), device=device)
        if world > 1:
            dist.all_reduce(finite, op=dist.ReduceOp.MIN)
        if not finite.item():
            raise FloatingPointError(f"Nonfinite gradient at update {step + 1}")
        optimizer.step()
        finite = (
            torch.stack([torch.isfinite(p).all() for p in model.parameters()])
            .all()
            .to(torch.int)
        )
        if world > 1:
            dist.all_reduce(finite, op=dist.ReduceOp.MIN)
        if not finite.item():
            raise FloatingPointError(f"Nonfinite parameters at update {step + 1}")
        accumulated_lr += current_lr
        if world > 1:
            dist.all_reduce(numerator_total)
        row = {
            "step": step + 1,
            "weighted_nll": float(numerator_total / denominator),
            "lr": current_lr,
            "epsilon": epsilon,
            "S": accumulated_lr,
            "gradient_norm_before_clip": float(norm),
            "input_tokens": (step + 1)
            * task.batch_size
            * task.accumulation
            * task.train_length
            * world,
            "seconds": prior_seconds + time.perf_counter() - tic,
            "phase": "natural_lm" if probability == 0 else "mixed_latest_write",
        }
        history.append(row)
        if rank == 0 and ((step + 1) % config.log_every == 0 or step == 0):
            print(json.dumps(row), flush=True)
        stopping = stop_after is not None and step + 1 >= stop_after
        milestone = step + 1 in (max(1, total // 2), total)
        if (step + 1) % config.checkpoint_every == 0 or milestone or stopping:
            row.update(gate_diagnostics(model, optimizer))
            local_rng = _rng_state(device)
            states = [None] * world if rank == 0 else None
            if world > 1:
                dist.gather_object(local_rng, states, dst=0)
            else:
                states = [local_rng]
            if rank == 0:
                payload = {
                    "model": model.state_dict(),
                    "model_config": asdict(model.config),
                    "optimizer": optimizer.state_dict(),
                    "step": step + 1,
                    "scheduler": {
                        "completed_updates": step + 1,
                        "S": accumulated_lr,
                        "lr": current_lr,
                        "epsilon": epsilon,
                    },
                    "S": accumulated_lr,
                    "rng_by_rank": states,
                    "history": history,
                    "signature": signature,
                    "specification": specification,
                    "seconds": row["seconds"],
                }
                if milestone:
                    model_only = {
                        k: payload[k]
                        for k in ("model", "model_config", "step", "S", "specification")
                    }
                    _save_checkpoint(
                        directory / f"checkpoint_{step + 1:06d}.pt", model_only
                    )
                _save_checkpoint(checkpoint, payload)
                _write_json(directory / "training.json", history)
                _write_json(
                    directory / "status.json",
                    {
                        "completed_steps": step + 1,
                        "total_steps": total,
                        "status": (
                            "complete" if step + 1 == total else "checkpoint_saved"
                        ),
                    },
                )
            if world > 1:
                dist.barrier()
        if stopping:
            break
    return {
        "checkpoint": str(checkpoint),
        "completed_steps": history[-1]["step"] if history else completed,
        "total_steps": total,
        "stage": stage,
        "gate": gate,
        "arm": arm,
    }
